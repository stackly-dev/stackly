/// `stackly instance create`.
#[derive(Debug, Args)]
pub struct CreateArgs {
    /// The unique instance name
    #[arg(value_name = "NAME")]
    pub name: String,
    /// The installed runtime to run it on: a runtime ID, or software@version such as postgresql@18
    #[arg(long, value_name = "RUNTIME")]
    pub runtime: RuntimeArg,
    /// The provider to create it from, such as official/postgresql; the one for the runtime by default
    #[arg(long, value_name = "NAMESPACE/NAME")]
    pub provider: Option<String>,
    /// The provider revision to pin; the revision of the catalog by default
    #[arg(long, value_name = "LABEL")]
    pub revision: Option<String>,
    /// The name to show
    #[arg(long, value_name = "TEXT")]
    pub display_name: Option<String>,
    /// A port for an endpoint: <endpoint>=<port> or <endpoint>=auto; repeat for more endpoints
    #[arg(long = "port", value_name = "ENDPOINT=PORT", action = ArgAction::Append)]
    pub ports: Vec<PortArg>,
    /// A settings field, read as the kind the form says: a number, true or false, or text; the last one for a field wins
    #[arg(long = "set", value_name = "FIELD=VALUE", action = ArgAction::Append)]
    pub settings: Vec<SettingArg>,
    /// A settings field with a JSON value, such as limits=[{"name":"a"}]; it wins over --set for the same field
    #[arg(long = "set-json", value_name = "FIELD=JSON", action = ArgAction::Append)]
    pub settings_json: Vec<SettingJsonArg>,
    /// A JSON file with the settings; --set and --set-json win over it for the same field
    #[arg(long, value_name = "PATH.JSON")]
    pub settings_file: Option<SettingsFileArg>,
    /// A secret field and where its value comes from: <field>=<generate|prompt|stdin|file:PATH|env:NAME|copy:REF|bind:REF>; a field left out is generated by the daemon
    #[arg(
        long = "secret",
        value_name = "FIELD=SOURCE",
        value_parser = secret_input::field_source,
        action = ArgAction::Append
    )]
    pub secrets: Vec<(String, SecretSource)>,
    /// Start the instance when the create has succeeded; waits for the create, and with --wait for the start too
    #[arg(long)]
    pub start: bool,
    /// Only judge the draft: print the preflight and exit 0 when it is ready, without creating anything
    #[arg(long)]
    pub dry_run: bool,
    /// `--wait`, `--timeout`, and `--idempotency-key`.
    #[command(flatten)]
    pub run: AsyncArgs,
}

/// The result of `create`: the operation, the instance, and with `--start`
/// the start; or with `--dry-run` the preflight.
#[derive(Debug, Clone, serde::Serialize)]
#[serde(untagged)]
pub enum CreateOutput {
    /// `--dry-run`.
    DryRun(DryRun),
    /// A create.
    Created(Box<Created>),
}

/// The `result` of `--dry-run`.
#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DryRun {
    /// What the daemon says about the draft.
    pub preflight: CreatePreflight,
}

/// The `result` of a create.
#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Created {
    /// The create, as for `start` and `stop`.
    #[serde(flatten)]
    pub action: InstanceAction,
    /// The start that followed, with `--start`.
    pub start: Option<StartInfo>,
}

/// The start `--start` sent after the create.
#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct StartInfo {
    /// The start operation, as accepted or with `--wait` as it ended.
    pub operation: Option<stackly_protocol::operation::OperationSummary>,
    /// The key of the start, derived from the key of the create.
    pub idempotency_key: String,
}

/// The secret sources `secrets` name, the last one for a field winning, in
/// the order the fields first appeared.
pub(super) fn latest_sources(secrets: &[(String, SecretSource)]) -> Vec<(&str, &SecretSource)> {
    let mut sources: Vec<(&str, &SecretSource)> = Vec::new();
    for (field, source) in secrets {
        match sources.iter_mut().find(|(known, _)| known == field) {
            Some(slot) => slot.1 = source,
            None => sources.push((field, source)),
        }
    }
    sources
}

fn check_stdin(sources: &[(&str, &SecretSource)]) -> Result<(), CliFailure> {
    let stdin = sources
        .iter()
        .filter(|(_, source)| matches!(source, SecretSource::Stdin))
        .count();
    if stdin > 1 {
        return Err(CliFailure::usage(
            "secret_stdin_twice",
            "only one --secret field can read from stdin",
        ));
    }
    Ok(())
}

/// Reads the value of every `--secret` flag, so a refused source stops
/// the command before it reaches the daemon.
///
/// # Errors
///
/// `cli.usage` when `stdin` names more than one field, and the errors
/// of [`secret_input::read_input`].
pub(super) fn read_secrets(
    cx: &mut Context,
    sources: &[(&str, &SecretSource)],
) -> Result<Vec<SecretFieldInput>, CliFailure> {
    check_stdin(sources)?;
    let mut inputs = Vec::new();
    for (field, source) in sources {
        let input =
            secret_input::read_input(cx, source, field, &mut Tty, &|name| std::env::var_os(name))?;
        inputs.push(SecretFieldInput {
            field: (*field).to_owned(),
            input,
        });
    }
    Ok(inputs)
}

/// The source of each `--secret` flag as a preflight plan: where the
/// value comes from, never the value.
pub(super) fn secret_plans(
    sources: &[(&str, &SecretSource)],
) -> Result<Vec<SecretPlan>, CliFailure> {
    check_stdin(sources)?;
    Ok(sources
        .iter()
        .map(|(field, source)| SecretPlan {
            field: (*field).to_owned(),
            source: plan_source(source),
        })
        .collect())
}

/// What a preflight plan says of a secret source.
pub(super) fn plan_source(source: &SecretSource) -> PlanSource {
    match source {
        SecretSource::Generate => PlanSource::Generate,
        SecretSource::Prompt
        | SecretSource::Stdin
        | SecretSource::File(_)
        | SecretSource::Env(_) => PlanSource::Value,
        SecretSource::CopyFrom(reference) => PlanSource::CopyFrom(reference.clone()),
        SecretSource::Bind(reference) => PlanSource::Bind(reference.clone()),
    }
}

impl CreateArgs {
    /// The secret sources these flags name, the last one for a field
    /// winning, in the order the fields first appeared.
    fn sources(&self) -> Vec<(&str, &SecretSource)> {
        latest_sources(&self.secrets)
    }

    /// The runtime ID: the one given, or the one `software@version` names
    /// among the installed runtimes of that software, the exact version
    /// first and the line second.
    async fn runtime_id(&self, cx: &mut Context) -> Result<Uuid, CliFailure> {
        let (software, version) = match &self.runtime {
            RuntimeArg::Id(id) => return Ok(*id),
            RuntimeArg::Selector { software, version } => (software, version),
        };
        let page = all_runtimes(cx).await?;
        let installed: Vec<_> = page
            .items
            .iter()
            .filter(|runtime| {
                runtime.state == RuntimeState::Installed && runtime.software == *software
            })
            .collect();
        let mut matches: Vec<Uuid> = installed
            .iter()
            .filter(|runtime| runtime.version == *version)
            .map(|runtime| runtime.id)
            .collect();
        if matches.is_empty() {
            matches = installed
                .iter()
                .filter(|runtime| runtime.line == *version)
                .map(|runtime| runtime.id)
                .collect();
        }
        match matches.as_slice() {
            [] => Err(CliFailure::runtime_not_found(&self.runtime.text())),
            [one] => Ok(*one),
            many => Err(CliFailure::runtime_ambiguous(&self.runtime.text(), many)),
        }
    }

    /// The settings document: the file first, then `--set` read as the
    /// kind the form says, then `--set-json`. A value that does not read as
    /// its kind goes as text, and a field the form does not know goes as it
    /// is, so the daemon refuses it with its own code.
    fn settings(&self, form: Option<&CreateForm>) -> SettingsDocument {
        let mut map = self
            .settings_file
            .as_ref()
            .map(|file| file.0.clone())
            .unwrap_or_default();
        for setting in &self.settings {
            let kind = form
                .and_then(|form| form.fields.iter().find(|field| field.key == setting.field))
                .map(|field| field.kind);
            map.insert(setting.field.clone(), typed(kind, &setting.value));
        }
        for setting in &self.settings_json {
            map.insert(setting.field.clone(), setting.value.clone());
        }
        SettingsDocument::new(map)
    }

    fn provider(&self, form: Option<&CreateForm>) -> ProviderSelector {
        ProviderSelector {
            name: self
                .provider
                .clone()
                .or_else(|| form.map(|form| form.provider.name.clone()))
                .unwrap_or_default(),
            revision: self.revision.clone(),
        }
    }

    fn endpoints(&self) -> Vec<EndpointRequest> {
        self.ports
            .iter()
            .map(|port| EndpointRequest {
                name: port.endpoint.clone(),
                port: port.port,
            })
            .collect()
    }

    /// The create form of the runtime. A daemon without a catalog, or whose
    /// catalog lacks the provider, has none; a command that names both the
    /// provider and its revision does not need it, because the daemon then
    /// uses the pinned package (spec 0020, *Resolusi provider dan
    /// revision*), and goes on without field kinds: `--set` values are sent
    /// as text, and the daemon judges the draft all the same.
    async fn form(
        &self,
        cx: &mut Context,
        runtime_id: Uuid,
    ) -> Result<Option<CreateForm>, CliFailure> {
        let call = Call::InstanceGetCreateForm(GetCreateFormParams {
            runtime_id,
            provider: self.provider.clone(),
        });
        match cx.call(call, CallSpec::control()).await {
            Ok(Reply::InstanceGetCreateForm(form)) => Ok(Some(*form)),
            Ok(_) => Err(CliFailure::unexpected_reply(None)),
            Err(failure)
                if matches!(
                    failure.body.code(),
                    "catalog.unavailable" | "instance.provider_not_found"
                ) && self.provider.is_some()
                    && self.revision.is_some() =>
            {
                Ok(None)
            }
            Err(failure) => Err(failure),
        }
    }

    async fn dry_run(
        &self,
        cx: &mut Context,
        runtime_id: Uuid,
        form: Option<&CreateForm>,
    ) -> CommandOutput<CreateOutput> {
        let secrets = match secret_plans(&self.sources()) {
            Ok(secrets) => secrets,
            Err(failure) => return CommandOutput::failed(failure),
        };
        let call = Call::InstancePreflight(PreflightCreateParams {
            name: self.name.clone(),
            display_name: self.display_name.clone(),
            provider: self.provider(form),
            runtime_id,
            endpoints: self.endpoints(),
            settings: self.settings(form),
            secrets,
            start: self.start,
        });
        let preflight = match cx.call(call, CallSpec::control()).await {
            Ok(Reply::InstancePreflight(preflight)) => *preflight,
            Ok(_) => return CommandOutput::failed(CliFailure::unexpected_reply(None)),
            Err(failure) => return CommandOutput::failed(failure),
        };
        let failure = first_error(&preflight);
        let output = DryRun { preflight };
        match failure {
            Some(failure) => CommandOutput::partial(CreateOutput::DryRun(output), failure),
            None => CommandOutput::ok(CreateOutput::DryRun(output)),
        }
    }
}

/// The start that follows a create that succeeded, with the key derived
/// from the key of the create so a repeated command starts once.
pub(super) async fn start_after(
    cx: &mut Context,
    wait: &AsyncArgs,
    created: &InstanceAction,
) -> (Option<StartInfo>, Option<CliFailure>) {
    let Some(id) = created
        .instance
        .as_ref()
        .map(|instance| instance.id)
        .or(created.instance_id)
    else {
        return (None, None);
    };
    let key = derived_start_key(&created.idempotency_key);
    let Ok(key) = key.parse() else {
        return (None, None);
    };
    let run = AsyncArgs {
        wait: wait.wait,
        idempotency_key: Some(key),
    };
    let call = Call::InstanceStart(StartInstanceParams {
        instance_id: id,
        expected_revision: None,
    });
    match cx.submit(call, &run, extract_start).await {
        Ok(submission) => (
            Some(StartInfo {
                operation: submission.operation,
                idempotency_key: submission.idempotency_key,
            }),
            submission.failure,
        ),
        Err(failure) => (None, Some(failure)),
    }
}

/// The key of the start that follows a create: the lowercase hex SHA-256 of
/// `<key of the create>:start`.
#[must_use]
pub fn derived_start_key(create_key: &str) -> String {
    Sha256::digest(format!("{create_key}:start").as_bytes())
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// `text` as the JSON value of a field of `kind`: a whole number, `true` or
/// `false`, or else text.
pub(super) fn typed(kind: Option<FieldKind>, text: &str) -> serde_json::Value {
    match kind {
        Some(FieldKind::Integer) => text
            .parse::<i64>()
            .map_or_else(|_| text.into(), serde_json::Value::from),
        Some(FieldKind::Boolean) => match text {
            "true" => serde_json::Value::Bool(true),
            "false" => serde_json::Value::Bool(false),
            _ => text.into(),
        },
        _ => text.into(),
    }
}

/// The error of the first failing row of `preflight`, which decides the
/// exit code of `--dry-run`; `None` when the draft is ready.
pub(super) fn first_error(preflight: &CreatePreflight) -> Option<CliFailure> {
    if preflight.ready {
        return None;
    }
    let error = preflight
        .checks
        .iter()
        .find(|check| check.status == PreflightStatus::Error)
        .and_then(|check| check.error.clone())?;
    Some(CliFailure::daemon(Box::new(error), None))
}

pub(super) fn extract(reply: Reply) -> Option<Accepted> {
    match reply {
        Reply::InstanceCreate(reply) => Some(accepted(&reply)),
        _ => None,
    }
}

impl RunCommand for CreateArgs {
    type Output = CreateOutput;

    async fn run(self, cx: &mut Context) -> CommandOutput<CreateOutput> {
        let runtime_id = match self.runtime_id(cx).await {
            Ok(id) => id,
            Err(failure) => return CommandOutput::failed(failure),
        };
        let form = match self.form(cx, runtime_id).await {
            Ok(form) => form,
            Err(failure) => return CommandOutput::failed(failure),
        };
        if self.dry_run {
            return self.dry_run(cx, runtime_id, form.as_ref()).await;
        }
        let secrets = match read_secrets(cx, &self.sources()) {
            Ok(secrets) => secrets,
            Err(failure) => return CommandOutput::failed(failure),
        };
        let params = CreateInstanceParams {
            name: self.name.clone(),
            display_name: self.display_name.clone(),
            provider: self.provider(form.as_ref()),
            runtime_id,
            endpoints: self.endpoints(),
            settings: self.settings(form.as_ref()),
            secrets,
        };
        // `--start` needs the create to end first, whatever `--wait` says.
        let mut run = self.run.clone();
        if self.start {
            run.wait.wait = true;
        }
        let submission = match cx.submit(Call::InstanceCreate(params), &run, extract).await {
            Ok(submission) => submission,
            Err(failure) => return CommandOutput::failed(failure),
        };
        let verb = Verb::Create {
            name: self.name.clone(),
        };
        let mut output = conclude(cx, submission, verb, None).await;
        let (start, start_failure) = match (&output.result, &output.failure) {
            (Some(created), None) if self.start && created.succeeded() => {
                start_after(cx, &self.run, created).await
            }
            _ => (None, None),
        };
        CommandOutput {
            result: output
                .result
                .take()
                .map(|action| CreateOutput::Created(Box::new(Created { action, start }))),
            failure: output.failure.take().or(start_failure),
            warnings: output.warnings,
            hints: output.hints,
        }
    }
}

impl Render for CreateOutput {
    fn render(&self, out: &mut HumanWriter) {
        match self {
            Self::DryRun(dry_run) => dry_run.render(out),
            Self::Created(created) => {
                created.action.render(out);
                if let Some(start) = &created.start {
                    match &start.operation {
                        Some(operation) => out.line(&format!(
                            "start operation {} {}",
                            operation.id,
                            crate::output::human::wire_name(&operation.state)
                        )),
                        None => out.line("already running"),
                    }
                }
            }
        }
    }
}

impl Render for DryRun {
    fn render(&self, out: &mut HumanWriter) {
        let preflight = &self.preflight;
        for check in &preflight.checks {
            out.line(&row(check));
        }
        for field in &preflight.fields {
            out.line(&format!(
                "{}: {}",
                escape_display(field.path()),
                escape_display(field.message())
            ));
        }
        out.line(if preflight.ready {
            "ready to create"
        } else {
            "not ready to create"
        });
        out.line(&format!("command: {}", escape_display(&preflight.command)));
    }
}

/// One line of the preflight: `ok`, `warn`, or `fail`, then the title and
/// the detail.
fn row(check: &PreflightCheck) -> String {
    let status = match check.status {
        PreflightStatus::Ok => "ok  ",
        PreflightStatus::Caution => "warn",
        _ => "fail",
    };
    format!(
        "{status} {}: {}",
        escape_display(&check.title),
        escape_display(&check.detail)
    )
}

