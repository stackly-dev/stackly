//! `stackly instance create` (spec 0014, AC-5). The flags map to the params
//! of `instance.create` as the table *Pemetaan flag create* says; the CLI
//! checks only the shape of what it was given.

use clap::{ArgAction, Args};
use stackly_protocol::instance::{
    CreateInstanceParams, EndpointRequest, ProviderSelector, SecretFieldInput, SettingsDocument,
};
use stackly_protocol::{Call, Reply};
use uuid::Uuid;

use super::{InstanceAction, Verb, accepted, conclude};
use crate::args::{self, PortArg, SettingArg, SettingJsonArg};
use crate::commands::RunCommand;
use crate::context::Context;
use crate::failure::CliFailure;
use crate::output::CommandOutput;
use crate::secret_input::{self, SecretSource, Tty};
use crate::wait::{Accepted, AsyncArgs};

// provisional: F20 (spec 0020 steps 9 and 10 replace the UUID only
// `--runtime`, the required `--provider` and `--revision`, and the
// text only `--set`)
/// `stackly instance create`.
#[derive(Debug, Args)]
pub struct CreateArgs {
    /// The unique instance name
    #[arg(value_name = "NAME")]
    pub name: String,
    /// The installed runtime to run it on, an ID printed by the seed or by runtime listings
    #[arg(long, value_name = "RUNTIME_ID", value_parser = args::runtime_id)]
    pub runtime: Uuid,
    /// The provider to create it from
    #[arg(long, value_name = "NAME")]
    pub provider: String,
    /// The provider revision to pin
    #[arg(long, value_name = "LABEL")]
    pub revision: String,
    /// The name to show
    #[arg(long, value_name = "TEXT")]
    pub display_name: Option<String>,
    /// A port for an endpoint: <endpoint>=<port> or <endpoint>=auto; repeat for more endpoints
    #[arg(long = "port", value_name = "ENDPOINT=PORT", action = ArgAction::Append)]
    pub ports: Vec<PortArg>,
    /// A settings field with a text value; the last one for a field wins
    #[arg(long = "set", value_name = "FIELD=TEXT", action = ArgAction::Append)]
    pub settings: Vec<SettingArg>,
    /// A settings field with a JSON value, such as readyDelayMs=1500; it wins over --set for the same field
    #[arg(long = "set-json", value_name = "FIELD=JSON", action = ArgAction::Append)]
    pub settings_json: Vec<SettingJsonArg>,
    /// A secret field and where its value comes from: <field>=<generate|prompt|stdin|file:PATH|env:NAME|copy:REF|bind:REF>; a field left out is generated by the daemon
    #[arg(
        long = "secret",
        value_name = "FIELD=SOURCE",
        value_parser = secret_input::field_source,
        action = ArgAction::Append
    )]
    pub secrets: Vec<(String, SecretSource)>,
    /// `--wait`, `--timeout`, and `--idempotency-key`.
    #[command(flatten)]
    pub run: AsyncArgs,
}

impl CreateArgs {
    /// The secret sources these flags name, the last one for a field
    /// winning, in the order the fields first appeared.
    fn sources(&self) -> Vec<(&str, &SecretSource)> {
        let mut sources: Vec<(&str, &SecretSource)> = Vec::new();
        for (field, source) in &self.secrets {
            match sources.iter_mut().find(|(known, _)| known == field) {
                Some(slot) => slot.1 = source,
                None => sources.push((field, source)),
            }
        }
        sources
    }

    /// Reads the value of every `--secret` flag, so a refused source stops
    /// the command before it reaches the daemon.
    ///
    /// # Errors
    ///
    /// `cli.usage` when `stdin` names more than one field, and the errors
    /// of [`secret_input::read_input`].
    fn read_secrets(&self, cx: &mut Context) -> Result<Vec<SecretFieldInput>, CliFailure> {
        let sources = self.sources();
        let stdin = sources
            .iter()
            .filter(|(_, source)| matches!(source, SecretSource::Stdin))
            .count();
        if stdin > 1 {
            return Err(CliFailure::usage(
                "secret_stdin_twice",
                "only one --secret field can read from stdin",
            ));
        }
        let mut inputs = Vec::with_capacity(sources.len());
        for (field, source) in sources {
            let input = secret_input::read_input(cx, source, field, &mut Tty, &|name| {
                std::env::var_os(name)
            })?;
            inputs.push(SecretFieldInput {
                field: field.to_owned(),
                input,
            });
        }
        Ok(inputs)
    }

    /// The params of `instance.create` these flags ask for, with the secret
    /// inputs already read.
    #[must_use]
    pub fn params(&self, secrets: Vec<SecretFieldInput>) -> CreateInstanceParams {
        let mut settings = serde_json::Map::new();
        for setting in &self.settings {
            settings.insert(
                setting.field.clone(),
                serde_json::Value::String(setting.value.clone()),
            );
        }
        for setting in &self.settings_json {
            settings.insert(setting.field.clone(), setting.value.clone());
        }
        CreateInstanceParams {
            name: self.name.clone(),
            display_name: self.display_name.clone(),
            provider: ProviderSelector {
                name: self.provider.clone(),
                revision: Some(self.revision.clone()),
            },
            runtime_id: self.runtime,
            endpoints: self
                .ports
                .iter()
                .map(|port| EndpointRequest {
                    name: port.endpoint.clone(),
                    port: port.port,
                })
                .collect(),
            settings: SettingsDocument::new(settings),
            secrets,
        }
    }
}

fn extract(reply: Reply) -> Option<Accepted> {
    match reply {
        Reply::InstanceCreate(reply) => Some(accepted(&reply)),
        _ => None,
    }
}

impl RunCommand for CreateArgs {
    type Output = InstanceAction;

    async fn run(self, cx: &mut Context) -> CommandOutput<InstanceAction> {
        let secrets = match self.read_secrets(cx) {
            Ok(secrets) => secrets,
            Err(failure) => return CommandOutput::failed(failure),
        };
        let call = Call::InstanceCreate(self.params(secrets));
        match cx.submit(call, &self.run, extract).await {
            Ok(submission) => {
                let verb = Verb::Create { name: self.name };
                conclude(cx, submission, verb, None).await
            }
            Err(failure) => CommandOutput::failed(failure),
        }
    }
}
