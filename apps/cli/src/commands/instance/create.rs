//! `stackly instance create` (spec 0014 AC-5, extended by spec 0020 AC-18).
//!
//! The command asks the daemon for the create form first, then builds the
//! params of `instance.preflight` (`--dry-run`) or `instance.create` from
//! the flags and the form. The CLI judges nothing of the draft: the daemon
//! does, once, for the sheet, for `--dry-run`, and for create alike. It only
//! refuses what the wire cannot carry (a port that is not a number, a JSON
//! that is not JSON, a file it cannot read) as `cli.usage`, before it calls
//! the daemon.

