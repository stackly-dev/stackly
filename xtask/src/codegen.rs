//! `cargo xtask codegen [--check | --amend]`: the Swift contract types,
//! the JSON Schemas, the error catalog, and the contract digest generated
//! from `stackly-protocol` (specs 0001 and 0006), plus the evidence JSON
//! Schemas generated from `stackly-evidence` (spec 0002).

mod contract;
mod swift;

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::Value;
use stackly_protocol::ProtocolVersion;

use contract::{ContractVersions, VersionsMode};

/// The `typeshare-cli` release the committed Swift file was generated with.
const TYPESHARE_CLI_VERSION: &str = "1.13.4";
const PROTOCOL_SRC: &str = "crates/protocol/src";
const TYPESHARE_CONFIG: &str = "typeshare.toml";
const SWIFT_OUTPUT: &str = "clients/swift/Sources/StacklyClient/Generated/StacklyProtocol.swift";
const OPEN_ENUMS_OUTPUT: &str = "clients/swift/Sources/StacklyClient/Generated/OpenEnums.swift";
const CONTRACT_INFO_OUTPUT: &str =
    "clients/swift/Sources/StacklyClient/Generated/ContractInfo.swift";
const DIGEST_OUTPUT: &str = "crates/protocol/src/contract_digest.rs";
const ERROR_CODES_OUTPUT: &str = "protocols/error-codes.json";
const VERSIONS_FILE: &str = "protocols/contract-versions.json";
const SCHEMA_DIR: &str = "protocols/schemas";
const EVIDENCE_SCHEMA_DIR: &str = "schemas/evidence";
/// Every folder whose `*.schema.json` files are all generated.
const SCHEMA_DIRS: [&str; 2] = [SCHEMA_DIR, EVIDENCE_SCHEMA_DIR];
const SCHEMA_SUFFIX: &str = ".schema.json";
/// The first line of every generated Rust or Swift file.
const GENERATED_HEADER: &str = "// @generated by cargo xtask codegen; do not edit\n";

/// Whether to write the generated files or only compare them.
pub enum Mode {
    /// Write every file. `amend` lets the digest recorded for
    /// `ProtocolVersion::CURRENT` change, for a version not on main yet.
    Write {
        amend: bool,
    },
    Check,
}

/// One generated file: its path relative to the repo root and its contents.
#[derive(Debug)]
struct Generated {
    path: PathBuf,
    contents: String,
}

pub fn run(root: &Path, mode: Mode) -> Result<()> {
    check_typeshare_version()?;
    let swift = generate_swift(root)?;
    let mut generated = vec![
        Generated {
            path: PathBuf::from(OPEN_ENUMS_OUTPUT),
            contents: swift::open_enums(&swift.contents),
        },
        swift,
    ];
    let (contract_files, digest) = generate_contract()?;
    generated.extend(contract_files);
    generated.extend(generate_schemas()?);
    let versions_mode = match mode {
        Mode::Write { amend } => VersionsMode::Write { amend },
        Mode::Check => VersionsMode::Check,
    };
    let versions = generate_versions(root, &digest, versions_mode);
    match mode {
        Mode::Write { .. } => {
            generated.push(versions?);
            write(root, &generated)
        }
        Mode::Check => match versions {
            Ok(file) => {
                generated.push(file);
                check(root, &generated)
            }
            Err(err) => {
                if let Err(drift) = check(root, &generated) {
                    eprintln!("{drift:#}");
                }
                Err(err)
            }
        },
    }
}

fn check_typeshare_version() -> Result<()> {
    let install = format!("cargo install --locked typeshare-cli --version {TYPESHARE_CLI_VERSION}");
    let output = Command::new("typeshare")
        .arg("--version")
        .output()
        .with_context(|| format!("cannot run `typeshare`; install it with `{install}`"))?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let found = stdout.split_whitespace().nth(1).unwrap_or("unknown");
    if !output.status.success() || found != TYPESHARE_CLI_VERSION {
        bail!(
            "typeshare-cli {TYPESHARE_CLI_VERSION} is required, found {found}; install it with `{install}`"
        );
    }
    Ok(())
}

fn generate_swift(root: &Path) -> Result<Generated> {
    let staging = tempfile::tempdir().context("cannot create a staging directory")?;
    let output = staging.path().join("StacklyProtocol.swift");
    let status = Command::new("typeshare")
        .arg(root.join(PROTOCOL_SRC))
        .args(["--lang", "swift"])
        .arg("--config-file")
        .arg(root.join(TYPESHARE_CONFIG))
        .arg("--output-file")
        .arg(&output)
        // typeshare logs every step at info level; keep only real problems.
        .env("RUST_LOG", "error")
        .status()
        .context("cannot run `typeshare`")?;
    if !status.success() {
        bail!("typeshare failed with {status}");
    }
    let contents =
        fs::read_to_string(&output).with_context(|| format!("cannot read {}", output.display()))?;
    Ok(Generated {
        path: PathBuf::from(SWIFT_OUTPUT),
        contents: format!("{GENERATED_HEADER}{contents}"),
    })
}

/// The files that carry the contract digest, the error catalog file, and
/// the digest itself. None of them needs typeshare.
fn generate_contract() -> Result<(Vec<Generated>, String)> {
    let schemas: Vec<(&str, Value)> = stackly_protocol::json_schemas()
        .into_iter()
        .map(|(stem, schema)| (stem, schema.as_value().clone()))
        .collect();
    let digest = contract::contract_digest(&schemas);
    let files = vec![
        Generated {
            path: PathBuf::from(DIGEST_OUTPUT),
            contents: digest_rs(&digest),
        },
        Generated {
            path: PathBuf::from(CONTRACT_INFO_OUTPUT),
            contents: swift::contract_info(&digest, ProtocolVersion::CURRENT),
        },
        Generated {
            path: PathBuf::from(ERROR_CODES_OUTPUT),
            contents: pretty_json(&contract::error_codes_file())?,
        },
    ];
    Ok((files, digest))
}

/// `crates/protocol/src/contract_digest.rs`, already in rustfmt's layout.
fn digest_rs(digest: &str) -> String {
    format!(
        "{GENERATED_HEADER}\n\
         /// SHA-256 of the normalized contract: every schema in `protocols/schemas/`\n\
         /// and the error catalog, without documentation text. Sent in the handshake\n\
         /// so peers with the same version but another contract see `contractDrift`.\n\
         pub const CONTRACT_DIGEST: &str =\n    \"{digest}\";\n"
    )
}

/// `protocols/contract-versions.json` after recording `digest` for
/// `ProtocolVersion::CURRENT`.
fn generate_versions(root: &Path, digest: &str, mode: VersionsMode) -> Result<Generated> {
    let path = root.join(VERSIONS_FILE);
    let record = if path.exists() {
        let text =
            fs::read_to_string(&path).with_context(|| format!("cannot read {}", path.display()))?;
        serde_json::from_str::<ContractVersions>(&text)
            .with_context(|| format!("{VERSIONS_FILE} is not a valid version record"))?
    } else {
        ContractVersions::default()
    };
    let record = contract::update_versions(record, ProtocolVersion::CURRENT, digest, mode)?;
    Ok(Generated {
        path: PathBuf::from(VERSIONS_FILE),
        contents: pretty_json(&record)?,
    })
}

fn pretty_json(value: &impl serde::Serialize) -> Result<String> {
    let mut contents = serde_json::to_string_pretty(value).context("cannot serialize json")?;
    contents.push('\n');
    Ok(contents)
}

fn generate_schemas() -> Result<Vec<Generated>> {
    let protocol = schema_files(SCHEMA_DIR, stackly_protocol::json_schemas())?;
    let evidence = schema_files(EVIDENCE_SCHEMA_DIR, stackly_evidence::json_schemas())?;
    Ok(protocol.into_iter().chain(evidence).collect())
}

fn schema_files(dir: &str, schemas: Vec<(&str, schemars::Schema)>) -> Result<Vec<Generated>> {
    schemas
        .into_iter()
        .map(|(stem, schema)| {
            let mut contents = serde_json::to_string_pretty(&schema)
                .with_context(|| format!("cannot serialize the {stem} schema"))?;
            contents.push('\n');
            Ok(Generated {
                path: Path::new(dir).join(format!("{stem}{SCHEMA_SUFFIX}")),
                contents,
            })
        })
        .collect()
}

fn write(root: &Path, generated: &[Generated]) -> Result<()> {
    for file in generated {
        let path = root.join(&file.path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("cannot create {}", parent.display()))?;
        }
        fs::write(&path, &file.contents)
            .with_context(|| format!("cannot write {}", path.display()))?;
        println!("wrote {}", file.path.display());
    }
    for stale in stale_schemas(root, generated)? {
        fs::remove_file(root.join(&stale))
            .with_context(|| format!("cannot remove {}", stale.display()))?;
        println!("removed {}", stale.display());
    }
    Ok(())
}

fn check(root: &Path, generated: &[Generated]) -> Result<()> {
    let mut drifted = Vec::new();
    for file in generated {
        let on_disk = fs::read_to_string(root.join(&file.path)).ok();
        if on_disk.as_deref() != Some(file.contents.as_str()) {
            drifted.push(file.path.clone());
        }
    }
    drifted.extend(stale_schemas(root, generated)?);
    if drifted.is_empty() {
        println!(
            "codegen: {} generated files are up to date",
            generated.len()
        );
        return Ok(());
    }
    for path in &drifted {
        eprintln!("  out of date: {}", path.display());
    }
    bail!(
        "generated files drifted from stackly-protocol or stackly-evidence; run `cargo xtask codegen` and commit the result"
    )
}

/// Schema files on disk that no type generates any more. Only the top level
/// of each schema folder is generated; `schemas/evidence/examples/` holds
/// hand written files and is left alone.
fn stale_schemas(root: &Path, generated: &[Generated]) -> Result<Vec<PathBuf>> {
    let mut stale = Vec::new();
    for schema_dir in SCHEMA_DIRS {
        let dir = root.join(schema_dir);
        if !dir.exists() {
            continue;
        }
        for entry in fs::read_dir(&dir).with_context(|| format!("cannot read {}", dir.display()))? {
            let name = entry?.file_name();
            let Some(name) = name.to_str() else { continue };
            let path = Path::new(schema_dir).join(name);
            if name.ends_with(SCHEMA_SUFFIX) && !generated.iter().any(|file| file.path == path) {
                stale.push(path);
            }
        }
    }
    Ok(stale)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> &'static Path {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("xtask sits one directory below the repository root")
    }

    /// The generated files that belong to `schemas/evidence/`.
    fn evidence_schemas() -> Vec<Generated> {
        generate_schemas()
            .unwrap()
            .into_iter()
            .filter(|file| file.path.starts_with(EVIDENCE_SCHEMA_DIR))
            .collect()
    }

    #[test]
    fn committed_contract_files_match_stackly_protocol() {
        let (mut files, digest) = generate_contract().unwrap();
        files.extend(
            generate_schemas()
                .unwrap()
                .into_iter()
                .filter(|file| file.path.starts_with(SCHEMA_DIR)),
        );
        files.push(generate_versions(repo_root(), &digest, VersionsMode::Check).unwrap());
        for file in files {
            let on_disk = fs::read_to_string(repo_root().join(&file.path)).unwrap();
            assert!(
                on_disk == file.contents,
                "{} drifted from stackly-protocol; run `cargo xtask codegen`",
                file.path.display()
            );
        }
        assert_eq!(stackly_protocol::CONTRACT_DIGEST, digest);
    }

    #[test]
    fn a_contract_change_without_a_new_version_fails_check_and_write_but_not_amend() {
        let root = tempfile::tempdir().unwrap();
        let protocols = root.path().join("protocols");
        fs::create_dir(&protocols).unwrap();
        let current = ProtocolVersion::CURRENT;
        let recorded = format!(
            r#"{{"versions":[{{"major":{},"minor":{},"digest":"{}"}}]}}"#,
            current.major,
            current.minor,
            "0".repeat(64)
        );
        fs::write(root.path().join(VERSIONS_FILE), recorded).unwrap();
        let digest = "1".repeat(64);

        let check = generate_versions(root.path(), &digest, VersionsMode::Check);
        assert!(check.is_err(), "check accepted a changed digest");
        let write = generate_versions(root.path(), &digest, VersionsMode::Write { amend: false });
        assert!(write.unwrap_err().to_string().contains("bump CURRENT"));
        let amended =
            generate_versions(root.path(), &digest, VersionsMode::Write { amend: true }).unwrap();
        assert!(amended.contents.contains(&digest));
        assert!(!amended.contents.contains(&"0".repeat(64)));
    }

    #[test]
    fn the_first_codegen_run_records_the_current_version() {
        let root = tempfile::tempdir().unwrap();
        let digest = "2".repeat(64);
        let file =
            generate_versions(root.path(), &digest, VersionsMode::Write { amend: false }).unwrap();
        let record: ContractVersions = serde_json::from_str(&file.contents).unwrap();
        assert_eq!(record.versions.len(), 1);
        assert_eq!(record.versions[0].digest, digest);
        assert!(generate_versions(root.path(), &digest, VersionsMode::Check).is_err());
    }

    #[test]
    fn the_protocol_schemas_are_protocol_version_request_and_server_frame() {
        let mut paths: Vec<_> = generate_schemas()
            .unwrap()
            .into_iter()
            .map(|file| file.path)
            .filter(|path| path.starts_with(SCHEMA_DIR))
            .collect();
        paths.sort();
        assert_eq!(
            paths,
            [
                "protocols/schemas/protocol-version.schema.json",
                "protocols/schemas/request.schema.json",
                "protocols/schemas/server-frame.schema.json",
            ]
            .map(PathBuf::from)
        );
    }

    #[test]
    fn generated_rust_and_swift_files_start_with_the_generated_header() {
        let (files, _) = generate_contract().unwrap();
        for file in files.iter().filter(|file| {
            file.path
                .extension()
                .is_some_and(|ext| ext == "rs" || ext == "swift")
        }) {
            assert!(
                file.contents.starts_with(GENERATED_HEADER),
                "{}",
                file.path.display()
            );
        }
    }

    #[test]
    fn the_four_evidence_schemas_are_generated_into_schemas_evidence() {
        let mut paths: Vec<_> = evidence_schemas()
            .into_iter()
            .map(|file| file.path)
            .collect();
        paths.sort();
        assert_eq!(
            paths,
            [
                "schemas/evidence/baseline-host.schema.json",
                "schemas/evidence/record.schema.json",
                "schemas/evidence/report.schema.json",
                "schemas/evidence/run-context.schema.json",
            ]
            .map(PathBuf::from)
        );
    }

    #[test]
    fn committed_evidence_schemas_match_the_rust_types() {
        for file in evidence_schemas() {
            let on_disk = fs::read_to_string(repo_root().join(&file.path)).unwrap();
            assert!(
                on_disk == file.contents,
                "{} drifted from stackly-evidence; run `cargo xtask codegen`",
                file.path.display()
            );
        }
    }

    #[test]
    fn check_flags_a_drifted_schema_and_a_stale_one_but_never_the_examples() {
        let root = tempfile::tempdir().unwrap();
        let generated = evidence_schemas();
        write(root.path(), &generated).unwrap();
        let examples = root.path().join(EVIDENCE_SCHEMA_DIR).join("examples");
        fs::create_dir(&examples).unwrap();
        fs::write(examples.join("record-rust-fixture-pass.json"), "{}\n").unwrap();
        assert!(check(root.path(), &generated).is_ok());

        let record = root.path().join("schemas/evidence/record.schema.json");
        fs::write(&record, "{}\n").unwrap();
        assert!(check(root.path(), &generated).is_err());

        write(root.path(), &generated).unwrap();
        let stale = root.path().join("schemas/evidence/old.schema.json");
        fs::write(&stale, "{}\n").unwrap();
        assert_eq!(
            stale_schemas(root.path(), &generated).unwrap(),
            [PathBuf::from("schemas/evidence/old.schema.json")]
        );
        assert!(check(root.path(), &generated).is_err());

        write(root.path(), &generated).unwrap();
        assert!(!stale.exists(), "write removes a schema no type generates");
        assert!(examples.join("record-rust-fixture-pass.json").exists());
        assert!(check(root.path(), &generated).is_ok());
    }
}
